import datetime
from typing import Optional, List
from sqlalchemy import (
    Integer,
    String,
    Text,
    Boolean,
    DateTime,
    Float,
    ForeignKey,
    Index,
)
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import relationship, Mapped, mapped_column
from app.db.base import Base


class ThreatAnalysisReport(Base):
    """
    Persisted threat modeling report generated by the LangGraph RAG pipeline with Grok.
    Maintains executive brief, technical attack chain, citations, and defensive recommendations.
    """
    __tablename__ = "threat_analysis_reports"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    report_id: Mapped[str] = mapped_column(String(100), unique=True, index=True, nullable=False)  # e.g., REP-2026-0010
    input_advisory: Mapped[str] = mapped_column(Text, nullable=False)
    report_title: Mapped[str] = mapped_column(String(300), nullable=False)
    executive_summary: Mapped[str] = mapped_column(Text, nullable=False)
    severity: Mapped[str] = mapped_column(String(50), default="High", index=True)  # Critical, High, Medium, Low
    severity_rationale: Mapped[Optional[str]] = mapped_column(Text)
    structured_report: Mapped[dict] = mapped_column(JSONB, nullable=False)  # Complete validated JSON schema output
    model_provider: Mapped[str] = mapped_column(String(100), default="xAI Grok")
    model_name: Mapped[str] = mapped_column(String(100), default="grok-4.7")
    completion_status: Mapped[str] = mapped_column(String(50), default="Completed", index=True)  # Completed, Partial, Insufficient Evidence, Error
    execution_duration_ms: Mapped[Optional[float]] = mapped_column(Float, default=0.0)
    is_demo: Mapped[bool] = mapped_column(Boolean, default=False, index=True)
    created_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.datetime.now(datetime.timezone.utc)
    )

    # Relationships
    citations: Mapped[List["AnalysisCitation"]] = relationship(
        "AnalysisCitation", back_populates="report", cascade="all, delete-orphan"
    )
    trace_steps: Mapped[List["AnalysisTraceStep"]] = relationship(
        "AnalysisTraceStep", back_populates="report", cascade="all, delete-orphan", order_by="AnalysisTraceStep.id"
    )


class AnalysisCitation(Base):
    """
    Observable evidence citations grounding the Grok LLM generation in authoritative
    MITRE ATT&CK, MITRE D3FEND, and CTI advisory source records.
    """
    __tablename__ = "analysis_citations"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    report_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("threat_analysis_reports.id", ondelete="CASCADE"), nullable=False, index=True
    )
    cited_source_id: Mapped[str] = mapped_column(String(150), index=True, nullable=False)
    external_id: Mapped[str] = mapped_column(String(100), index=True, nullable=False)  # e.g., T1078, D3-MFA
    source_url: Mapped[Optional[str]] = mapped_column(String(500))
    excerpt: Mapped[str] = mapped_column(Text, nullable=False)
    relevance_score: Mapped[Optional[float]] = mapped_column(Float, default=1.0)
    citation_role: Mapped[str] = mapped_column(String(50), default="Technique Evidence")  # Technique Evidence, Countermeasure, Procedure Example

    # Relationships
    report: Mapped[ThreatAnalysisReport] = relationship(ThreatAnalysisReport, back_populates="citations")


class AnalysisTraceStep(Base):
    """
    Step-by-step observable LangGraph execution trace.
    Records duration, status, retrieved counts, and sanitized metadata without sensitive secrets.
    """
    __tablename__ = "analysis_trace_steps"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    report_id: Mapped[int] = mapped_column(
        Integer, ForeignKey("threat_analysis_reports.id", ondelete="CASCADE"), nullable=False, index=True
    )
    step_name: Mapped[str] = mapped_column(String(100), index=True, nullable=False)
    status: Mapped[str] = mapped_column(String(50), default="SUCCESS")  # SUCCESS, SKIPPED, FAILED
    started_at: Mapped[datetime.datetime] = mapped_column(
        DateTime(timezone=True), default=lambda: datetime.datetime.now(datetime.timezone.utc)
    )
    completed_at: Mapped[Optional[datetime.datetime]] = mapped_column(DateTime(timezone=True))
    duration_ms: Mapped[float] = mapped_column(Float, default=0.0)
    trace_metadata: Mapped[Optional[dict]] = mapped_column(JSONB, default=dict)
    error_details: Mapped[Optional[str]] = mapped_column(Text)

    # Relationships
    report: Mapped[ThreatAnalysisReport] = relationship(ThreatAnalysisReport, back_populates="trace_steps")

    __table_args__ = (
        Index("idx_trace_report_step", "report_id", "step_name"),
    )
